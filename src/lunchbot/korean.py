def stems(token: str) -> list[str]:
    """낱말과, 뒤에 붙은 조사·'이다'를 하나 또는 둘 떼어 낸 꼴들 ("끝이야" → 끝이야, 끝, …)."""
    out, todo = [token], [token]
    for _ in range(2):  # "정리라서는" 처럼 둘까지
        nxt = []
        for word in todo:
            for end in ENDINGS:
                if word.endswith(end) and len(word) > len(end):
                    nxt.append(word[: -len(end)])
        out += nxt
        todo = nxt
    return out


def common(token: str) -> bool:
    """기본 낱말인지 (조사를 떼어 한 글자만 남아도 기본 낱말로 봄: "끝이야" → 끝)."""
    return any(s in WORDS or len(s) < 2 for s in stems(token) if s != token) or token in WORDS
